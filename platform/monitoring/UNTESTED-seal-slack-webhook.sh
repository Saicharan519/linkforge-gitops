#!/usr/bin/env bash
# ======================================================================================================
# UNTESTED. Written in P8.3 but NEVER RUN: there is no Slack workspace (decision D79). Slack delivery of
# alerts has NOT been tested. Only `bash -n` (syntax) was checked.
# ======================================================================================================
#
# What it does: asks for a Slack incoming-webhook URL with a HIDDEN prompt (nothing is echoed or put in the
# shell history or process list), seals it with the cluster's Sealed Secrets controller and writes
# CIPHERTEXT to platform/monitoring/extras/alertmanager-slack.sealedsecret.yaml (strict scope: name
# alertmanager-slack, namespace monitoring, key `webhook-url`).
#
# What it does NOT do (still to design and test when a workspace exists):
#   - tell Alertmanager to use the secret: the chart needs `alertmanager.config` with a slack receiver whose
#     `api_url_file` points at the mounted secret (alertmanager.alertmanagerSpec.secrets: [alertmanager-slack]);
#   - send a test alert and check that a message arrives in Slack.
#
# Usage (kind only):  platform/monitoring/UNTESTED-seal-slack-webhook.sh   then commit the generated file.
set -euo pipefail
export PATH="$HOME/.local/bin:$PATH"
CTX=kind-linkforge
OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/extras/alertmanager-slack.sealedsecret.yaml"

read -r -s -p "Slack webhook URL (input hidden): " url
echo
case "$url" in
  https://hooks.slack.com/services/*) ;;
  *) echo "that does not look like a Slack incoming-webhook URL; nothing written" >&2; exit 1 ;;
esac

{
  echo "# GENERATED by UNTESTED-seal-slack-webhook.sh with kubeseal (strict scope: alertmanager-slack / monitoring)."
  echo "# Ciphertext only. Not yet referenced by any Alertmanager config."
  printf 'apiVersion: v1\nkind: Secret\nmetadata:\n  name: alertmanager-slack\n  namespace: monitoring\ntype: Opaque\nstringData:\n  webhook-url: %s\n' "$url" \
    | kubeseal --context "$CTX" --controller-name sealed-secrets-controller --controller-namespace kube-system --format yaml
} > "$OUT"
unset url
echo "wrote $OUT (ciphertext only)"
